def runs_sub(text, sz=None, do_typo=True):
    """Нижние индексы S_{вн} и верхние Z^{−2}."""
    out = []
    mode = "subscript"
    for i, part in enumerate(re.split(r"([_^])\{([^}]*)\}", text)):
        if i % 3 == 0:
            out.append(_runs(part, sz, do_typo) if part else "")
        elif i % 3 == 1:
            mode = "subscript" if part == "_" else "superscript"
        else:
            size = f'<w:sz w:val="{sz}"/><w:szCs w:val="{sz}"/>' if sz else ""
            out.append(f'<w:r><w:rPr><w:vertAlign w:val="{mode}"/>{size}</w:rPr>'
                       f'<w:t xml:space="preserve">{td.esc(part)}</w:t></w:r>')
    return "".join(out)


